const Mobile = require("../model/mobile")

exports.getMobile = async (req,res) => {
    try {
        const data = await Mobile.find()
        return res.json({errors:false,data:data})
    } catch (error) {
        return res.status(500).json({errors:true,message:error.message})
    }
}

exports.postMobile = async (req,res) => {
    try {
        const data = await Mobile.create(req.body)
        return res.json({errors:false,data:data})
    } catch (error) {
        return res.status(500).json({errors:true,message:error.message})
    }
}

exports.putMobile = async (req,res) => {
    try {
        const data = await Mobile.findByIdAndUpdate(req.params.id,req.body,{new:true})
        return res.json({errors:false,data:data})
    } catch (error) {
        return res.status(500).json({errors:true,message:error.message})
    }
}

exports.deleteMobile = async (req,res) => {
    try {
        const data = await Mobile.findByIdAndDelete(req.params.id)
        return res.json({errors:false,data:data})
    } catch (error) {
        return res.status(500).json({errors:true,message:error.message})
    }
}